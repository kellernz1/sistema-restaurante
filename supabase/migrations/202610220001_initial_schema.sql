create or replace function public.set_order_lifecycle_timestamps()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if old.status = 'pending_confirmation' and new.status = 'open' and new.confirmed_at is null then
    new.confirmed_at := now();
  end if;

  if new.status = 'closed' and old.status <> 'closed' and new.closed_at is null then
    new.closed_at := now();
  end if;

  return new;
end;
$$;

create trigger set_order_lifecycle_timestamps_before_update
  before update of status on public.orders
  for each row execute function public.set_order_lifecycle_timestamps();

create or replace function public.sync_dine_in_table_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.order_type <> 'dine_in' then
    return new;
  end if;

  if new.status not in ('closed', 'cancelled') then
    update public.tables set status = 'occupied' where id = new.table_id;
  elsif not exists (
    select 1
    from public.orders
    where table_id = new.table_id
      and id <> new.id
      and order_type = 'dine_in'
      and status not in ('closed', 'cancelled')
  ) then
    update public.tables set status = 'available' where id = new.table_id;
  end if;

  return new;
end;
$$;

create trigger sync_dine_in_table_status_after_order_write
  after insert or update of status on public.orders
  for each row execute function public.sync_dine_in_table_status();

create or replace function public.can_update_table(p_new public.tables)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  old_row public.tables;
  actor_role public.user_role;
begin
  actor_role := public.current_user_role();
  if actor_role = 'admin' then
    return true;
  end if;

  select * into old_row from public.tables where id = p_new.id;
  return actor_role in ('waiter', 'cashier')
    and (to_jsonb(p_new) - 'status') = (to_jsonb(old_row) - 'status');
end;
$$;

create or replace function public.can_update_order(p_new public.orders)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  old_row public.orders;
  actor_role public.user_role;
  unchanged_except_managed_fields boolean;
begin
  actor_role := public.current_user_role();
  if actor_role = 'admin' then
    return true;
  end if;

  select * into old_row from public.orders where id = p_new.id;
  if actor_role = 'waiter' then
    unchanged_except_managed_fields :=
      (to_jsonb(p_new) - 'status' - 'cancel_reason' - 'confirmed_at')
      =
      (to_jsonb(old_row) - 'status' - 'cancel_reason' - 'confirmed_at');

    if not unchanged_except_managed_fields then
      return false;
    end if;

    return (
      old_row.status = 'pending_confirmation'
      and p_new.status in ('open', 'cancelled')
    ) or (
      old_row.status = 'open'
      and p_new.status = 'cancelled'
    );
  end if;

  if actor_role = 'cashier' then
    unchanged_except_managed_fields :=
      (
        to_jsonb(p_new)
        - 'status'
        - 'cancel_reason'
        - 'confirmed_at'
        - 'closed_at'
        - 'payment_method'
        - 'payment_status'
        - 'cash_change_for'
      )
      =
      (
        to_jsonb(old_row)
        - 'status'
        - 'cancel_reason'
        - 'confirmed_at'
        - 'closed_at'
        - 'payment_method'
        - 'payment_status'
        - 'cash_change_for'
      );

    if not unchanged_except_managed_fields then
      return false;
    end if;

    return (old_row.status = p_new.status)
      or (old_row.status = 'pending_confirmation' and p_new.status in ('open', 'cancelled'))
      or (old_row.status = 'open' and p_new.status in ('ready', 'closed', 'cancelled'))
      or (old_row.status = 'ready' and p_new.status in ('out_for_delivery', 'closed', 'cancelled'))
      or (old_row.status = 'out_for_delivery' and p_new.status in ('closed', 'cancelled'));
  end if;

  return false;
end;
$$;

create or replace function public.can_update_order_item(p_new public.order_items)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  old_row public.order_items;
  actor_role public.user_role;
begin
  actor_role := public.current_user_role();
  if actor_role = 'admin' then
    return true;
  end if;

  select * into old_row from public.order_items where id = p_new.id;

  if (to_jsonb(p_new) - 'status' - 'updated_at')
    <> (to_jsonb(old_row) - 'status' - 'updated_at') then
    return false;
  end if;

  if actor_role = 'waiter' then
    return old_row.status = 'ready' and p_new.status = 'delivered';
  end if;

  return actor_role = 'kitchen';
end;
$$;

create or replace function public.open_table(p_table_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_table public.tables;
  created_order public.orders;
  actor_role public.user_role;
begin
  actor_role := public.current_user_role();
  if auth.uid() is null or actor_role not in ('admin', 'waiter') then
    raise exception 'Not authorized to open a table' using errcode = '42501';
  end if;

  select * into selected_table
  from public.tables
  where id = p_table_id
  for update;

  if not found then
    raise exception 'Table not found' using errcode = 'P0002';
  end if;

  if selected_table.status <> 'available' then
    raise exception 'Table is not available' using errcode = 'P0001';
  end if;

  insert into public.orders (order_type, source, table_id, waiter_id, status, confirmed_at)
  values ('dine_in', 'waiter', p_table_id, auth.uid(), 'open', now())
  returning * into created_order;

  update public.tables set status = 'occupied' where id = p_table_id;

  return created_order;
exception
  when unique_violation then
    raise exception 'Table already has an active order' using errcode = 'P0001';
end;
$$;

create or replace function public.close_order(p_order_id uuid, p_payment_method text)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_order public.orders;
  closed_order public.orders;
  selected_payment_method public.payment_method;
  actor_role public.user_role;
begin
  actor_role := public.current_user_role();
  if auth.uid() is null or actor_role not in ('admin', 'cashier') then
    raise exception 'Not authorized to close orders' using errcode = '42501';
  end if;

  begin
    selected_payment_method := p_payment_method::public.payment_method;
  exception
    when invalid_text_representation then
      raise exception 'Invalid payment method' using errcode = '22023';
  end;

  select * into target_order
  from public.orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Order not found' using errcode = 'P0002';
  end if;

  if target_order.status in ('closed', 'cancelled') then
    raise exception 'Order is already closed or cancelled' using errcode = 'P0001';
  end if;

  perform public.recompute_order_total(p_order_id);

  update public.orders
  set status = 'closed',
      payment_method = selected_payment_method,
      payment_status = 'paid',
      closed_at = now()
  where id = p_order_id
  returning * into closed_order;

  if closed_order.order_type = 'dine_in' then
    update public.tables set status = 'available' where id = closed_order.table_id;
  end if;

  return closed_order;
end;
$$;

create or replace function public.create_customer_order(p_payload jsonb)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  settings public.restaurant_settings;
  requested_type public.order_type;
  requested_source public.order_source;
  requested_table_id uuid;
  requested_payment_method public.payment_method;
  requested_change numeric(10, 2);
  matched_customer_id uuid;
  item jsonb;
  item_product_id uuid;
  item_quantity integer;
  item_price numeric(10, 2);
  subtotal numeric(10, 2) := 0;
  target_order public.orders;
  selected_table public.tables;
  initial_status public.order_status;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Only the service role can create customer orders' using errcode = '42501';
  end if;

  if jsonb_typeof(p_payload) <> 'object' then
    raise exception 'Payload must be a JSON object' using errcode = '22023';
  end if;

  begin
    requested_type := (p_payload ->> 'order_type')::public.order_type;
    requested_source := (p_payload ->> 'source')::public.order_source;
    requested_table_id := nullif(p_payload ->> 'table_id', '')::uuid;
    requested_payment_method := nullif(p_payload ->> 'payment_method', '')::public.payment_method;
    requested_change := nullif(p_payload ->> 'cash_change_for', '')::numeric(10, 2);
  exception
    when invalid_text_representation or numeric_value_out_of_range then
      raise exception 'Payload contains an invalid enum, UUID, or numeric value' using errcode = '22023';
  end;

  if requested_type is null or requested_source is null then
    raise exception 'Order type and source are required' using errcode = '22023';
  end if;

  if requested_source not in ('qr', 'nfc', 'whatsapp', 'web') then
    raise exception 'Invalid customer order source' using errcode = '22023';
  end if;

  if (requested_type = 'dine_in' and requested_source not in ('qr', 'nfc', 'whatsapp'))
    or (requested_type in ('pickup', 'delivery') and requested_source not in ('web', 'whatsapp')) then
    raise exception 'Order type and source are incompatible' using errcode = '22023';
  end if;

  if jsonb_typeof(p_payload -> 'items') <> 'array'
    or jsonb_array_length(p_payload -> 'items') = 0
    or jsonb_array_length(p_payload -> 'items') > 100 then
    raise exception 'An order must contain between 1 and 100 items' using errcode = '22023';
  end if;

  select * into settings
  from public.restaurant_settings
  where id = true
  for share;

  if not found or not settings.is_accepting_orders then
    raise exception 'Restaurant is not accepting orders' using errcode = 'P0001';
  end if;

  if requested_type = 'dine_in' then
    if requested_table_id is null then
      raise exception 'Dine-in orders require a table' using errcode = '22023';
    end if;
    if requested_source in ('qr', 'nfc') and not settings.dine_in_qr_enabled then
      raise exception 'Table self-service is disabled' using errcode = 'P0001';
    end if;
  elsif requested_type = 'pickup' and not settings.pickup_enabled then
    raise exception 'Pickup orders are disabled' using errcode = 'P0001';
  elsif requested_type = 'delivery' and not settings.delivery_enabled then
    raise exception 'Delivery orders are disabled' using errcode = 'P0001';
  end if;

  if requested_type in ('pickup', 'delivery') then
    if nullif(btrim(p_payload ->> 'customer_name'), '') is null
      or nullif(btrim(p_payload ->> 'customer_phone'), '') is null then
      raise exception 'Customer name and phone are required' using errcode = '22023';
    end if;
    if (p_payload ->> 'customer_phone') !~ '^\+[1-9][0-9]{7,14}$' then
      raise exception 'Customer phone must use E.164 format' using errcode = '22023';
    end if;
  end if;

  if requested_type = 'delivery'
    and (
      p_payload -> 'delivery_address' is null
      or jsonb_typeof(p_payload -> 'delivery_address') <> 'object'
    ) then
    raise exception 'Delivery orders require an address' using errcode = '22023';
  end if;

  if requested_change is not null
    and (requested_payment_method is distinct from 'cash' or requested_change < 0) then
    raise exception 'Change amount is only valid for cash payments' using errcode = '22023';
  end if;

  for item in select value from jsonb_array_elements(p_payload -> 'items')
  loop
    begin
      item_product_id := (item ->> 'product_id')::uuid;
      item_quantity := (item ->> 'quantity')::integer;
    exception
      when invalid_text_representation or numeric_value_out_of_range then
        raise exception 'Invalid product or quantity' using errcode = '22023';
    end;

    if item_quantity <= 0 then
      raise exception 'Item quantity must be positive' using errcode = '22023';
    end if;

    select price into item_price
    from public.products
    where id = item_product_id and is_active;

    if not found then
      raise exception 'Product % is inactive or does not exist', item_product_id using errcode = '23514';
    end if;

    subtotal := subtotal + (item_price * item_quantity);
  end loop;

  if requested_type = 'delivery' and subtotal < settings.min_delivery_order then
    raise exception 'Delivery minimum order value was not reached' using errcode = 'P0001';
  end if;

  if requested_type in ('pickup', 'delivery') then
    select id into matched_customer_id
    from public.customers
    where phone = p_payload ->> 'customer_phone';
  end if;

  if requested_type = 'dine_in' then
    select * into selected_table
    from public.tables
    where id = requested_table_id
    for update;

    if not found then
      raise exception 'Table not found' using errcode = 'P0002';
    end if;

    if selected_table.status = 'closing' then
      raise exception 'Table is closing and cannot receive new items' using errcode = 'P0001';
    end if;

    select * into target_order
    from public.orders
    where table_id = requested_table_id
      and order_type = 'dine_in'
      and status not in ('closed', 'cancelled')
    for update;

    if not found then
      initial_status := case
        when settings.require_confirmation_for_qr then 'pending_confirmation'::public.order_status
        else 'open'::public.order_status
      end;

      insert into public.orders (
        order_type,
        source,
        table_id,
        customer_name,
        notes,
        status,
        confirmed_at
      ) values (
        'dine_in',
        requested_source,
        requested_table_id,
        nullif(btrim(p_payload ->> 'customer_name'), ''),
        nullif(btrim(p_payload ->> 'notes'), ''),
        initial_status,
        case when initial_status = 'open' then now() else null end
      )
      returning * into target_order;
    elsif target_order.status = 'ready' then
      update public.orders
      set status = 'open'
      where id = target_order.id
      returning * into target_order;
    end if;
  else
    insert into public.orders (
      order_type,
      source,
      customer_id,
      customer_name,
      customer_phone,
      delivery_address,
      delivery_fee,
      notes,
      payment_method,
      cash_change_for,
      status
    ) values (
      requested_type,
      requested_source,
      matched_customer_id,
      btrim(p_payload ->> 'customer_name'),
      p_payload ->> 'customer_phone',
      case when requested_type = 'delivery' then p_payload -> 'delivery_address' else null end,
      case when requested_type = 'delivery' then settings.delivery_fee else 0 end,
      nullif(btrim(p_payload ->> 'notes'), ''),
      requested_payment_method,
      requested_change,
      'pending_confirmation'
    )
    returning * into target_order;
  end if;

  for item in select value from jsonb_array_elements(p_payload -> 'items')
  loop
    insert into public.order_items (order_id, product_id, quantity, unit_price, notes)
    values (
      target_order.id,
      (item ->> 'product_id')::uuid,
      (item ->> 'quantity')::integer,
      0,
      nullif(btrim(item ->> 'notes'), '')
    );
  end loop;

  select * into target_order from public.orders where id = target_order.id;
  return target_order;
end;
$$;

