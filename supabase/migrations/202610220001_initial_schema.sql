  before update on public.order_items
  for each row execute function public.set_order_item_updated_at();

create or replace function public.recompute_order_total(p_order_id uuid)
returns numeric
language plpgsql
security definer
set search_path = ''
as $$
declare
  computed_total numeric(10, 2);
begin
  update public.orders as target
  set total_amount = coalesce(
    (
      select sum(item.quantity * item.unit_price)
      from public.order_items as item
      where item.order_id = p_order_id
    ),
    0
  ) + target.delivery_fee
  where target.id = p_order_id
  returning target.total_amount into computed_total;

  return computed_total;
end;
$$;

create or replace function public.recompute_order_total_from_item()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    perform public.recompute_order_total(old.order_id);
    return old;
  end if;

  perform public.recompute_order_total(new.order_id);

  if tg_op = 'UPDATE' and old.order_id <> new.order_id then
    perform public.recompute_order_total(old.order_id);
  end if;

  return new;
end;
$$;

create trigger recompute_order_total_after_item_write
  after insert or update or delete on public.order_items
  for each row execute function public.recompute_order_total_from_item();

