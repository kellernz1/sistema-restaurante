begin;

create extension if not exists pgcrypto with schema extensions;

create type public.user_role as enum ('admin', 'waiter', 'kitchen', 'cashier');
create type public.table_status as enum ('available', 'occupied', 'closing');
create type public.order_type as enum ('dine_in', 'pickup', 'delivery');
create type public.order_source as enum ('waiter', 'qr', 'nfc', 'whatsapp', 'web');
create type public.order_status as enum (
  'pending_confirmation',
  'open',
  'ready',
  'out_for_delivery',
  'closed',
  'cancelled'
);
create type public.payment_method as enum ('cash', 'card', 'pix');
create type public.payment_status as enum ('pending', 'paid');
create type public.order_item_status as enum ('pending', 'preparing', 'ready', 'delivered');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role public.user_role not null default 'waiter',
  created_at timestamptz not null default now()
);

create table public.tables (
  id uuid primary key default gen_random_uuid(),
  table_number integer not null unique check (table_number > 0),
  capacity integer not null check (capacity > 0),
  status public.table_status not null default 'available',
  qr_token text not null unique default encode(extensions.gen_random_bytes(32), 'hex'),
  constraint tables_qr_token_entropy check (length(qr_token) >= 32)
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(btrim(name)) > 0),
  sort_order integer not null default 0
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid not null references public.categories(id) on delete restrict,
  name text not null check (length(btrim(name)) > 0),
  price numeric(10, 2) not null check (price >= 0),
  description text,
  is_active boolean not null default true
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  phone text not null unique,
  name text,
  created_at timestamptz not null default now(),
  constraint customers_phone_e164 check (phone ~ '^\+[1-9][0-9]{7,14}$')
);

create table public.customer_addresses (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete cascade,
  label text,
  street text not null,
  number text not null,
  complement text,
  neighborhood text not null,
  city text not null,
  state text not null check (state ~ '^[A-Z]{2}$'),
  zip_code text not null check (zip_code ~ '^[0-9]{8}$'),
  reference text,
  created_at timestamptz not null default now()
);

create table public.restaurant_settings (
  id boolean primary key default true check (id),
  is_accepting_orders boolean not null default true,
  dine_in_qr_enabled boolean not null default true,
  require_confirmation_for_qr boolean not null default true,
  pickup_enabled boolean not null default true,
  delivery_enabled boolean not null default true,
  delivery_fee numeric(10, 2) not null default 0 check (delivery_fee >= 0),
  min_delivery_order numeric(10, 2) not null default 0 check (min_delivery_order >= 0),
  estimated_pickup_minutes integer not null default 30 check (estimated_pickup_minutes > 0),
  estimated_delivery_minutes integer not null default 50 check (estimated_delivery_minutes > 0),
  whatsapp_enabled boolean not null default false
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  public_token text not null unique default encode(extensions.gen_random_bytes(32), 'hex'),
  order_type public.order_type not null,
  source public.order_source not null,
  table_id uuid references public.tables(id) on delete restrict,
  waiter_id uuid references public.profiles(id) on delete set null,
  customer_id uuid references public.customers(id) on delete set null,
  customer_name text,
  customer_phone text,
  delivery_address jsonb,
  delivery_fee numeric(10, 2) not null default 0 check (delivery_fee >= 0),
  total_amount numeric(10, 2) not null default 0 check (total_amount >= 0),
  notes text,
  payment_method public.payment_method,
  payment_status public.payment_status not null default 'pending',
  cash_change_for numeric(10, 2) check (cash_change_for is null or cash_change_for >= 0),
  status public.order_status not null default 'open',
  cancel_reason text,
  created_at timestamptz not null default now(),
  confirmed_at timestamptz,
  closed_at timestamptz,
  constraint orders_public_token_entropy check (length(public_token) >= 32),
  constraint orders_type_fields check (
    (order_type = 'dine_in' and table_id is not null)
    or
    (order_type = 'pickup' and customer_name is not null and customer_phone is not null)
    or
    (
      order_type = 'delivery'
      and customer_name is not null
      and customer_phone is not null
      and delivery_address is not null
      and jsonb_typeof(delivery_address) = 'object'
    )
  ),
  constraint orders_non_dine_in_without_table check (order_type = 'dine_in' or table_id is null),
  constraint orders_customer_phone_e164 check (
    customer_phone is null or customer_phone ~ '^\+[1-9][0-9]{7,14}$'
  ),
  constraint orders_delivery_status check (status <> 'out_for_delivery' or order_type = 'delivery'),
  constraint orders_cancel_reason check (status <> 'cancelled' or nullif(btrim(cancel_reason), '') is not null),
  constraint orders_cash_change check (
    cash_change_for is null or payment_method = 'cash'
  )
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10, 2) not null default 0 check (unit_price >= 0),
  status public.order_item_status not null default 'pending',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index orders_one_active_dine_in_per_table_idx
  on public.orders (table_id)
  where order_type = 'dine_in' and status not in ('closed', 'cancelled');

create index products_category_id_idx on public.products(category_id);
create index products_active_idx on public.products(is_active) where is_active;
create index customer_addresses_customer_id_idx on public.customer_addresses(customer_id);
create index orders_table_id_idx on public.orders(table_id);
create index orders_waiter_id_idx on public.orders(waiter_id);
create index orders_customer_id_idx on public.orders(customer_id);
create index orders_status_idx on public.orders(status);
create index orders_type_status_idx on public.orders(order_type, status);
create index orders_created_at_idx on public.orders(created_at desc);
create index order_items_order_id_idx on public.order_items(order_id);
create index order_items_product_id_idx on public.order_items(product_id);
create index order_items_status_idx on public.order_items(status);

